/**
 * Generate packages/db/src/types.gen.ts from the migrations — no Docker or Supabase login needed.
 * Boots PGlite, applies migrations, introspects the public schema and emits the same shape as
 * `supabase gen types typescript`. Run: pnpm --filter @dudu/db gen:types
 * (Equivalent once linked: npx supabase gen types typescript --linked > packages/db/src/types.gen.ts)
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { createTestDb, DB_ROOT } from "../src/testing";

const db = await createTestDb();

const enums = (
  await db.query<{ name: string; labels: string[] }>(`
    select t.typname as name, array_agg(e.enumlabel order by e.enumsortorder) as labels
    from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
    where n.nspname = 'public' group by t.typname order by t.typname`)
).rows;
const enumNames = new Set(enums.map((e) => e.name));

const columns = (
  await db.query<{
    table_name: string;
    column_name: string;
    udt_name: string;
    data_type: string;
    is_nullable: string;
    column_default: string | null;
  }>(`
    select c.table_name, c.column_name, c.udt_name, c.data_type, c.is_nullable, c.column_default
    from information_schema.columns c
    join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
    where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
    order by c.table_name, c.ordinal_position`)
).rows;

const fks = (
  await db.query<{
    table_name: string;
    name: string;
    columns: string[];
    ref_table: string;
    ref_columns: string[];
    one_to_one: boolean;
  }>(`
    select cl.relname as table_name, con.conname as name,
      array(select a.attname from unnest(con.conkey) k join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k) as columns,
      rcl.relname as ref_table,
      array(select a.attname from unnest(con.confkey) k join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k) as ref_columns,
      exists (
        select 1 from pg_index i where i.indrelid = con.conrelid and i.indisunique and i.indpred is null
          and (select array_agg(x order by x) from unnest(i.indkey) x) = (select array_agg(y order by y) from unnest(con.conkey) y)
      ) as one_to_one
    from pg_constraint con
    join pg_class cl on cl.oid = con.conrelid join pg_namespace n on n.oid = cl.relnamespace
    join pg_class rcl on rcl.oid = con.confrelid join pg_namespace rn on rn.oid = rcl.relnamespace
    where con.contype = 'f' and n.nspname = 'public' and rn.nspname = 'public'
    order by cl.relname, con.conname`)
).rows;

const functions = (
  await db.query<{
    name: string;
    arg_names: string[] | null;
    arg_types: string[];
    n_defaults: number;
    return_type: string;
  }>(`
    select p.proname as name, p.proargnames as arg_names,
      array(select format_type(t, null) from unnest(p.proargtypes) t) as arg_types,
      p.pronargdefaults as n_defaults, format_type(p.prorettype, null) as return_type
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.prokind = 'f' and format_type(p.prorettype, null) <> 'trigger'
    order by p.proname`)
).rows;

await db.close();

function tsType(udt: string): string {
  const isArray = udt.startsWith("_");
  const base = isArray ? udt.slice(1) : udt;
  let t: string;
  if (enumNames.has(base)) t = `Database["public"]["Enums"]["${base}"]`;
  else if (
    [
      "int2",
      "int4",
      "int8",
      "numeric",
      "float4",
      "float8",
      "integer",
      "bigint",
      "smallint",
      "double precision",
      "real",
    ].includes(base)
  )
    t = "number";
  else if (["bool", "boolean"].includes(base)) t = "boolean";
  else if (["json", "jsonb"].includes(base)) t = "Json";
  else if (base === "void") t = "undefined";
  else t = "string";
  return isArray ? `${t}[]` : t;
}

function fnType(pgType: string): string {
  const isArray = pgType.endsWith("[]");
  const base = pgType.replace(/\[\]$/, "").replace(/^public\./, "");
  const map: Record<string, string> = {
    uuid: "uuid",
    text: "text",
    integer: "int4",
    boolean: "bool",
    jsonb: "jsonb",
    json: "json",
    date: "date",
    "timestamp with time zone": "timestamptz",
    void: "void",
    numeric: "numeric",
  };
  return tsType((isArray ? "_" : "") + (map[base] ?? base));
}

const byTable = new Map<string, typeof columns>();
for (const c of columns) byTable.set(c.table_name, [...(byTable.get(c.table_name) ?? []), c]);

const I = (n: number) => "  ".repeat(n);
let out = `// AUTO-GENERATED by packages/db/scripts/gen-types.ts from migrations. Do not edit.
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  public: {
    Tables: {
`;
for (const [table, cols] of byTable) {
  const row = cols
    .map(
      (c) =>
        `${I(5)}${c.column_name}: ${tsType(c.udt_name)}${c.is_nullable === "YES" ? " | null" : ""};`,
    )
    .join("\n");
  const ins = cols
    .map((c) => {
      const optional = c.is_nullable === "YES" || c.column_default !== null;
      return `${I(5)}${c.column_name}${optional ? "?" : ""}: ${tsType(c.udt_name)}${c.is_nullable === "YES" ? " | null" : ""};`;
    })
    .join("\n");
  const upd = cols
    .map(
      (c) =>
        `${I(5)}${c.column_name}?: ${tsType(c.udt_name)}${c.is_nullable === "YES" ? " | null" : ""};`,
    )
    .join("\n");
  const rels = fks
    .filter((f) => f.table_name === table)
    .map(
      (f) => `${I(5)}{
${I(6)}foreignKeyName: "${f.name}";
${I(6)}columns: [${f.columns.map((c) => `"${c}"`).join(", ")}];
${I(6)}isOneToOne: ${f.one_to_one};
${I(6)}referencedRelation: "${f.ref_table}";
${I(6)}referencedColumns: [${f.ref_columns.map((c) => `"${c}"`).join(", ")}];
${I(5)}},`,
    )
    .join("\n");
  out += `${I(3)}${table}: {
${I(4)}Row: {
${row}
${I(4)}};
${I(4)}Insert: {
${ins}
${I(4)}};
${I(4)}Update: {
${upd}
${I(4)}};
${I(4)}Relationships: [${rels ? `\n${rels}\n${I(4)}` : ""}];
${I(3)}};
`;
}
out += `${I(2)}};
${I(2)}Views: { [_ in never]: never };
${I(2)}Functions: {
`;
for (const f of functions) {
  const names = (f.arg_names ?? []).slice(0, f.arg_types.length);
  const firstDefault = f.arg_types.length - f.n_defaults;
  const args = f.arg_types.length
    ? `{ ${f.arg_types.map((t, i) => `${names[i] ?? `arg${i}`}${i >= firstDefault ? "?" : ""}: ${fnType(t)}`).join("; ")} }`
    : "Record<PropertyKey, never>";
  out += `${I(3)}${f.name}: { Args: ${args}; Returns: ${fnType(f.return_type)} };\n`;
}
out += `${I(2)}};
${I(2)}Enums: {
${enums.map((e) => `${I(3)}${e.name}: ${e.labels.map((l) => JSON.stringify(l)).join(" | ")};`).join("\n")}
${I(2)}};
${I(2)}CompositeTypes: { [_ in never]: never };
${I(1)}};
};

type PublicSchema = Database["public"];
export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];
export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];
export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];
export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T];

export const Constants = {
  public: {
    Enums: {
${enums.map((e) => `${I(3)}${e.name}: [${e.labels.map((l) => JSON.stringify(l)).join(", ")}],`).join("\n")}
    },
  },
} as const;
`;

const target = join(DB_ROOT, "src", "types.gen.ts");
writeFileSync(target, out);
console.info(
  `Wrote ${target} (${byTable.size} tables, ${enums.length} enums, ${functions.length} functions)`,
);
